/**
 * RFC 5545 iCalendar generator for VPS expiry events.
 *
 * Pure module — no DOM, no chrome.* — so it can be loaded in the popup,
 * options page, and unit-tested in Node. The download helper (downloadICS)
 * is the only part that touches the DOM and is only called from the UI.
 */

// Escape text values per RFC 5545 (backslash, semicolon, comma, newlines).
function escapeICalText(text) {
  if (text === null || text === undefined) return '';
  return String(text)
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r?\n/g, '\\n');
}

// 'YYYY-MM-DDTHH:MM:SSZ' style UTC timestamp used for DTSTAMP.
function icsDateTimeStamp(d) {
  return d.toISOString().replace(/[-:]/g, '').replace(/\.\d{3}Z$/, 'Z');
}

// 'YYYY-MM-DD' -> 'YYYYMMDD' (DATE value).
function icsDateOnly(isoDate) {
  return String(isoDate).replace(/[-:]/g, '').slice(0, 8);
}

// Add N days to an ISO date, return 'YYYY-MM-DD' (TZ-safe, UTC-based).
function icsAddDays(isoDate, days) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(isoDate || '');
  if (!m) return isoDate;
  const dt = new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3])));
  dt.setUTCDate(dt.getUTCDate() + days);
  const y = dt.getUTCFullYear();
  const mo = String(dt.getUTCMonth() + 1).padStart(2, '0');
  const da = String(dt.getUTCDate()).padStart(2, '0');
  return `${y}-${mo}-${da}`;
}

function icsDateValid(d) {
  if (!d || typeof d !== 'string') return false;
  const dt = new Date(d.length === 10 ? d + 'T00:00:00' : d);
  return !isNaN(dt.getTime());
}

// Fold lines at 75 octets (RFC 5545 §3.1) — safe for ASCII content.
function foldICalLine(line) {
  if (line.length <= 75) return line;
  const out = [line.slice(0, 75)];
  let rest = line.slice(75);
  while (rest.length > 74) {
    out.push(' ' + rest.slice(0, 74));
    rest = rest.slice(74);
  }
  if (rest.length) out.push(' ' + rest);
  return out.join('\r\n');
}

// Build a single VEVENT (with one VALARM per reminder threshold) for a server.
function buildVEvent(server, thresholds, dtstamp) {
  const uid = 'vps-dashboard-' + (server.id || 'server') + '@vps-dashboard';
  const start = icsDateOnly(server.expiryDate);
  // DTEND is exclusive for all-day events → add one day.
  const end = icsDateOnly(icsAddDays(server.expiryDate, 1));
  const summary = escapeICalText((server.name || 'VPS') + ' · ' + (server.providerName || 'VPS'));

  const descriptionParts = [];
  if (server.providerName) descriptionParts.push('Provider: ' + server.providerName);
  if (server.url) descriptionParts.push('URL: ' + server.url);
  descriptionParts.push('Auto-generated by VPS Dashboard. API-sourced dates may be inaccurate — please verify manually.');
  const description = escapeICalText(descriptionParts.join('\n'));

  const lines = [
    'BEGIN:VEVENT',
    'UID:' + uid,
    'DTSTAMP:' + dtstamp,
    'DTSTART;VALUE=DATE:' + start,
    'DTEND;VALUE=DATE:' + end,
    'SUMMARY:' + summary,
    'DESCRIPTION:' + description,
    'STATUS:CONFIRMED',
    'TRANSP:OPAQUE'
  ];

  (thresholds || []).slice().sort((a, b) => a - b).forEach(T => {
    lines.push('BEGIN:VALARM');
    lines.push('ACTION:DISPLAY');
    lines.push('TRIGGER:-P' + T + 'D');
    lines.push('DESCRIPTION:' + escapeICalText((server.name || 'VPS') + ' expires in ' + T + ' days'));
    lines.push('END:VALARM');
  });

  lines.push('END:VEVENT');
  return lines.map(foldICalLine).join('\r\n');
}

// Build a full VCALENDAR string from a list of servers.
// Each server may carry: id, name, providerName, url, expiryDate, expirySource.
function buildICS(servers, opts) {
  opts = opts || {};
  const thresholds = (opts.thresholds && opts.thresholds.length)
    ? opts.thresholds
    : [3, 7, 30];
  const dtstamp = icsDateTimeStamp(opts.now || new Date());

  const events = (servers || [])
    .filter(s => s && s.expiryDate && icsDateValid(s.expiryDate))
    .map(s => buildVEvent(s, thresholds, dtstamp));

  const cal = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//VPS Dashboard//Expiry Calendar//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH'
  ].concat(events, ['END:VCALENDAR']);

  return cal.join('\r\n') + '\r\n';
}

// Trigger a browser download of the .ics content (popup / options only).
function downloadICS(filename, content) {
  const blob = new Blob([content], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
